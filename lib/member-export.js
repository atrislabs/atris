'use strict';

// `atris member export`: each active atris/team/<member>/MEMBER.md becomes a
// native subagent file for the coding tools that read one.
//
//   claude  .claude/agents/<name>.md   markdown, YAML frontmatter (name, description, model)
//   cursor  .cursor/agents/<name>.md   same markdown shape; cursor-agent globs **/.cursor/agents/**/*.md
//   codex   .codex/agents/<name>.toml  agent role file (name, description, developer_instructions);
//                                      codex 0.162 discovers roles in .codex/agents
//
// Every file carries GENERATED_MARK. Export only overwrites or removes files
// that carry it, so a hand-written agent with the same name is left alone.
// Parked members are skipped, and their old generated files are removed.

const fs = require('fs');
const path = require('path');
const { isParkedText } = require('./member-park');

const GENERATED_MARK = 'generated by atris member export';
const TARGETS = ['claude', 'cursor', 'codex'];
const SKIP_DIRS = new Set(['_template', '_archive', '_archived']);

function frontmatterOf(text) {
  const match = String(text || '').replace(/^﻿/, '').match(/^---\r?\n([\s\S]*?)\r?\n---[ \t]*(?:\r?\n|$)/);
  if (!match) return { fields: {}, body: String(text || '') };
  const fields = {};
  let listKey = null;
  for (const line of match[1].split(/\r?\n/)) {
    const item = line.match(/^\s+-\s+(.+)$/);
    if (item && listKey) {
      fields[listKey].push(item[1].trim().replace(/^["']|["']$/g, ''));
      continue;
    }
    const kv = line.match(/^([a-zA-Z_-]+):\s*(.*)$/);
    if (!kv) continue;
    const value = kv[2].replace(/\s+#.*$/, '').trim();
    if (value === '') {
      fields[kv[1]] = [];
      listKey = kv[1];
    } else if (value.startsWith('[') && value.endsWith(']')) {
      fields[kv[1]] = value.slice(1, -1).split(',').map((s) => s.trim().replace(/^["']|["']$/g, '')).filter(Boolean);
      listKey = null;
    } else {
      fields[kv[1]] = value.replace(/^["']|["']$/g, '');
      listKey = null;
    }
  }
  return { fields, body: String(text).replace(/^﻿/, '').slice(match[0].length) };
}

function scalar(value) {
  return typeof value === 'string' ? value.trim() : '';
}

function listOf(value) {
  return Array.isArray(value) ? value.filter((v) => typeof v === 'string' && v.trim()) : [];
}

// Skills named in frontmatter plus any skills/<name>/SKILL.md on disk.
function memberSkills(dir, fields) {
  const names = new Set(listOf(fields.skills));
  const skillsDir = path.join(dir, 'skills');
  try {
    for (const entry of fs.readdirSync(skillsDir)) {
      if (fs.existsSync(path.join(skillsDir, entry, 'SKILL.md'))) names.add(entry);
    }
  } catch {}
  return [...names].sort();
}

function readMembers(root) {
  const teamDir = path.join(root, 'atris', 'team');
  let entries = [];
  try {
    entries = fs.readdirSync(teamDir).sort();
  } catch {
    return { members: [], parked: [] };
  }
  const members = [];
  const parked = [];
  for (const entry of entries) {
    if (SKIP_DIRS.has(entry) || entry.startsWith('.')) continue;
    const dir = path.join(teamDir, entry);
    const file = path.join(dir, 'MEMBER.md');
    let text;
    try {
      text = fs.readFileSync(file, 'utf8');
    } catch {
      continue;
    }
    if (isParkedText(text)) {
      parked.push(entry);
      continue;
    }
    const { fields, body } = frontmatterOf(text);
    members.push({
      slug: entry,
      role: scalar(fields.role),
      description: scalar(fields.description),
      model: scalar(fields.model),
      skills: memberSkills(dir, fields),
      body: body.trim(),
    });
  }
  return { members, parked };
}

// Claude Code wants lowercase letters, digits, and hyphens; codex allows
// letters, digits, spaces, hyphens, and underscores. One safe form fits both.
function agentName(slug) {
  return String(slug).toLowerCase().replace(/[^a-z0-9-]+/g, '-').replace(/^-+|-+$/g, '') || 'member';
}

// Written for the tool's router: what the member does, then when to hand it work.
function agentDescription(member) {
  const what = member.description.replace(/\s+/g, ' ').trim();
  const role = member.role || member.slug;
  const lead = what ? (/[.!?]$/.test(what) ? what : `${what}.`) : `The ${role} on this project's Atris team.`;
  return `${lead} Use this agent when a task fits the ${role} role on this project's Atris team.`;
}

function instructions(member) {
  const lines = [
    `You are ${member.slug}, the ${member.role || member.slug} on this project's Atris team.`,
    `Your full card is atris/team/${member.slug}/MEMBER.md; read it when this summary is not enough.`,
    '',
  ];
  if (member.body) lines.push(member.body, '');
  if (member.skills.length) {
    lines.push('## Skills', '');
    for (const skill of member.skills) {
      lines.push(`- ${skill}: atris/team/${member.slug}/skills/${skill}/SKILL.md`);
    }
    lines.push('');
  }
  return lines.join('\n').trimEnd() + '\n';
}

function markdownAgent(member, { withModel }) {
  const source = `atris/team/${member.slug}/MEMBER.md`;
  const front = [
    '---',
    `# ${GENERATED_MARK} from ${source}. edit MEMBER.md; this file gets overwritten.`,
    `name: ${agentName(member.slug)}`,
    `description: ${JSON.stringify(agentDescription(member))}`,
  ];
  if (withModel && member.model) front.push(`model: ${JSON.stringify(member.model)}`);
  front.push('---', '', '');
  return front.join('\n') + instructions(member);
}

// TOML basic strings take the same escapes JSON.stringify emits.
function codexAgent(member) {
  const source = `atris/team/${member.slug}/MEMBER.md`;
  return [
    `# ${GENERATED_MARK} from ${source}. edit MEMBER.md; this file gets overwritten.`,
    `name = ${JSON.stringify(agentName(member.slug))}`,
    `description = ${JSON.stringify(agentDescription(member))}`,
    `developer_instructions = ${JSON.stringify(instructions(member))}`,
    '',
  ].join('\n');
}

const FORMATS = {
  claude: { dir: ['.claude', 'agents'], ext: '.md', render: (m) => markdownAgent(m, { withModel: true }) },
  cursor: { dir: ['.cursor', 'agents'], ext: '.md', render: (m) => markdownAgent(m, { withModel: false }) },
  codex: { dir: ['.codex', 'agents'], ext: '.toml', render: codexAgent },
};

function isGenerated(file) {
  try {
    return fs.readFileSync(file, 'utf8').slice(0, 400).includes(GENERATED_MARK);
  } catch {
    return false;
  }
}

function exportMembers(root, { targets = TARGETS, dryRun = false } = {}) {
  const { members, parked } = readMembers(root);
  const result = { members: members.map((m) => m.slug), parked, written: [], unchanged: [], removed: [], kept: [] };
  if (!fs.existsSync(path.join(root, 'atris', 'team'))) return result;

  for (const target of targets) {
    const format = FORMATS[target];
    if (!format) continue;
    const dir = path.join(root, ...format.dir);
    const wanted = new Set();
    for (const member of members) {
      const file = path.join(dir, agentName(member.slug) + format.ext);
      const rel = path.relative(root, file);
      wanted.add(file);
      const next = format.render(member);
      if (fs.existsSync(file)) {
        if (!isGenerated(file)) {
          result.kept.push(rel);
          continue;
        }
        if (fs.readFileSync(file, 'utf8') === next) {
          result.unchanged.push(rel);
          continue;
        }
      }
      if (!dryRun) {
        fs.mkdirSync(dir, { recursive: true });
        fs.writeFileSync(file, next, 'utf8');
      }
      result.written.push(rel);
    }
    // A member that was parked or removed leaves no stale generated file behind.
    let existing = [];
    try {
      existing = fs.readdirSync(dir);
    } catch {}
    for (const entry of existing) {
      const file = path.join(dir, entry);
      if (!entry.endsWith(format.ext) || wanted.has(file) || !isGenerated(file)) continue;
      if (!dryRun) fs.unlinkSync(file);
      result.removed.push(path.relative(root, file));
    }
  }
  return result;
}

function summaryLine(result, { dryRun = false } = {}) {
  const count = result.members.length;
  const parts = [`${count} ${count === 1 ? 'member' : 'members'} exported to claude code, cursor, and codex`];
  if (result.written.length) parts.push(`${result.written.length} ${dryRun ? 'would change' : 'files written'}`);
  if (result.removed.length) parts.push(`${result.removed.length} old ${dryRun ? 'would be removed' : 'removed'}`);
  if (!result.written.length && !result.removed.length) parts.push('already up to date');
  if (result.parked.length) parts.push(`${result.parked.length} parked skipped`);
  return parts.join(', ');
}

module.exports = {
  GENERATED_MARK,
  TARGETS,
  agentDescription,
  agentName,
  exportMembers,
  frontmatterOf,
  readMembers,
  summaryLine,
};

test('land in empty repo prints one-line error without stack', () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'atris-land-empty-'));
  try {
    spawnSync('git', ['init', '-b', 'main', '-q'], { cwd: dir });
    const result = run(['land'], dir);
    assert.equal(result.status, 1);
    const err = `${result.stderr || ''}${result.stdout || ''}`;
    assert.match(err, /no commits yet/i);
    assert.doesNotMatch(err, /at Object\.landCommand|Error: no master/);
    assert.doesNotMatch(err, /node:internal/);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

test('recap does not claim tests passed for a file-exists verifier', () => {
  const { buildRecapData, renderShare, renderRecap } = require('../commands/recap');
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'atris-recap-file-'));
  try {
    process.env.ATRIS_TASKS_DB = path.join(dir, 'tasks.db');
    const taskDb = require('../lib/task-db');
    taskDb.close();
    const db = taskDb.open(path.join(dir, 'tasks.db'));
    const ws = taskDb.workspaceRoot(dir);
    const { id } = taskDb.addTask(db, { title: 'Ship a note', workspaceRoot: ws, status: 'open' });
    taskDb.readyTask(db, {
      id,
      actor: 'tester',
      proof: '[verified] `test -f note.md` passed (exit 0)\nReceipt: /tmp/x.json',
    });
    db.prepare('UPDATE tasks SET status = ?, done_at = ?, updated_at = ? WHERE id = ?')
      .run('done', Date.now(), Date.now(), id);
    const data = buildRecapData(dir, { days: 7 });
    const share = renderShare(data);
    const recap = renderRecap(data);
    assert.doesNotMatch(share, /tests passed/i);
    assert.doesNotMatch(recap, /tests passed/i);
    assert.match(`${share}\n${recap}`, /test -f note\.md|file check/i);
  } finally {
    delete process.env.ATRIS_TASKS_DB;
    require('../lib/task-db').close();
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

// These cases exercise prompt preparation only. No journal is created, so
// today's date cannot select content or trigger the handoff/learning paths.
async function reviewFiles(files) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'review-atris-'));
  const previousCwd = process.cwd();
  const previousArgv = process.argv;
  const previousEnv = { ...process.env };
  const previousLog = console.log;
  const lines = [];
  try {
    for (const name of Object.keys(process.env)) {
      if (name.startsWith('ATRIS_')) delete process.env[name];
    }
    process.env.HOME = root;
    process.env.ATRIS_NONINTERACTIVE = '1';
    process.chdir(root);
    process.argv = [process.execPath, 'atris', 'review', '--verbose'];
    fs.mkdirSync(path.join(root, 'atris'));
    for (const [name, content] of Object.entries(files)) {
      const target = path.join(root, name);
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, content);
    }
    console.log = (...args) => lines.push(args.join(' '));
    const { reviewAtris } = require('../commands/workflow');
    const result = await reviewAtris();
    assert.strictEqual(result, undefined);
    assert.strictEqual(fs.existsSync(path.join(root, 'atris', 'logs')), false);
    return lines.join('\n');
  } finally {
    console.log = previousLog;
    process.argv = previousArgv;
    process.chdir(previousCwd);
    for (const name of Object.keys(process.env)) {
      if (!(name in previousEnv)) delete process.env[name];
    }
    Object.assign(process.env, previousEnv);
    fs.rmSync(root, { recursive: true, force: true });
  }
}

test('reviewAtris prepares the preferred validator, guide and task context', async () => {
  const output = await reviewFiles({
    'atris/team/validator/MEMBER.md': 'preferred validator instructions',
    'atris/team/validator.md': 'obsolete validator instructions',
    'AGENT_TESTING_GUIDE.md': 'preferred testing instructions',
    'TESTING_GUIDE.md': 'lower priority testing instructions',
    'atris/TODO.md': 'current task context',
    'atris/TASK_CONTEXTS.md': 'obsolete task context',
    'atris/MAP.md': 'routing map',
    'atris/features/example/validate.md': 'check example',
    'atris/features/_template/validate.md': 'ignore template',
  });
  assert.ok(output.includes('Validator spec: atris/team/validator/MEMBER.md'));
  assert.ok(output.includes('preferred validator instructions'));
  assert.ok(output.includes('preferred testing instructions'));
  assert.ok(output.includes('current task context'));
  assert.ok(output.includes('Feature validate scripts found: 1'));
  assert.ok(output.includes('- atris/features/example/validate.md'));
  assert.ok(!output.includes('obsolete validator instructions'));
  assert.ok(!output.includes('lower priority testing instructions'));
  assert.ok(!output.includes('obsolete task context'));
  assert.ok(!output.includes('_template/validate.md'));
});

test('reviewAtris falls back to legacy context and flags a placeholder map', async () => {
  const output = await reviewFiles({
    'atris/team/validator.md': 'legacy validator instructions',
    'atris/TASK_CONTEXTS.md': 'legacy task instructions',
    'atris/TESTING_GUIDE.md': 'workspace testing instructions',
    'atris/MAP.md': 'Generated by your AI agent after reading atris.md',
  });
  assert.ok(output.includes('Validator spec: atris/team/validator.md'));
  assert.ok(output.includes('legacy validator instructions'));
  assert.ok(output.includes('TODO: atris/TASK_CONTEXTS.md'));
  assert.ok(output.includes('legacy task instructions'));
  assert.ok(output.includes('workspace testing instructions'));
  assert.ok(output.includes('MAP: atris/MAP.md (placeholder, generate first)'));
  assert.ok(output.includes('generate it from `atris/atris.md`'));
});

test('reviewAtris tolerates missing optional context and malformed config', async () => {
  const output = await reviewFiles({ 'atris/.config': '{invalid json' });
  assert.ok(output.includes('You are the Validator.'));
  assert.ok(output.includes('Validator spec: atris/team/validator/MEMBER.md (missing)'));
  assert.ok(output.includes('Testing guide: (none found)'));
  assert.ok(output.includes('MAP: atris/MAP.md (missing)'));
  assert.ok(output.includes('TODO: atris/TODO.md (missing)'));
  assert.ok(output.includes('Feature validate scripts found: 0'));
  assert.ok(!output.includes('TESTING GUIDE (full):'));
  assert.ok(!output.includes('any learnings?'));
});

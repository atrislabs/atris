'use strict';

// `atris member export` turns each active MEMBER.md into a subagent file for
// Claude Code, Cursor, and Codex, skips parked members, and never touches a
// hand-written agent file.

const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const test = require('node:test');
const assert = require('node:assert/strict');
const { spawnSync } = require('node:child_process');

const { GENERATED_MARK, exportMembers, frontmatterOf } = require('../lib/member-export');

const cli = path.resolve(__dirname, '..', 'bin', 'atris.js');

function project(members) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'member-export-'));
  for (const [name, text, skills = []] of members) {
    const dir = path.join(root, 'atris', 'team', name);
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, 'MEMBER.md'), text);
    for (const skill of skills) {
      fs.mkdirSync(path.join(dir, 'skills', skill), { recursive: true });
      fs.writeFileSync(path.join(dir, 'skills', skill, 'SKILL.md'), `# ${skill}\n`);
    }
  }
  return root;
}

const VALIDATOR = '---\nname: validator\nrole: Reviewer\ndescription: Validate execution, run tests, "ensure" quality\nmodel: opus\nskills:\n  - test-runner\n---\n\n# Validator\n\n## Rules\n\n- Never patch, only judge.\n';
const SCOUT = '---\nname: scout\nrole: Scout\ndescription: Finds new signal\nstatus: parked\nparked_note: 2026-10-01 quiet\n---\n\n# Scout\n';

test('writes claude, cursor, and codex agents from MEMBER.md and skips parked members', () => {
  const root = project([['validator', VALIDATOR, ['cross-model-referee']], ['scout', SCOUT]]);
  const result = exportMembers(root);

  assert.deepEqual(result.members, ['validator']);
  assert.deepEqual(result.parked, ['scout']);
  assert.deepEqual(result.written.sort(), ['.claude/agents/validator.md', '.codex/agents/validator.toml', '.cursor/agents/validator.md']);
  for (const tool of ['.claude', '.cursor', '.codex']) {
    assert.equal(fs.readdirSync(path.join(root, tool, 'agents')).some((f) => f.startsWith('scout')), false);
  }

  const claude = fs.readFileSync(path.join(root, '.claude', 'agents', 'validator.md'), 'utf8');
  assert.match(claude, /^---\n# generated by atris member export from atris\/team\/validator\/MEMBER\.md/);
  const { fields, body } = frontmatterOf(claude);
  assert.equal(fields.name, 'validator');
  assert.match(fields.description, /Validate execution/);
  assert.match(fields.description, /Use this agent when a task fits the Reviewer role/);
  assert.equal(fields.model, 'opus');
  assert.match(body, /## Rules\n\n- Never patch, only judge\./);
  assert.match(body, /- cross-model-referee: atris\/team\/validator\/skills\/cross-model-referee\/SKILL\.md/);
  assert.match(body, /- test-runner: atris\/team\/validator\/skills\/test-runner\/SKILL\.md/);

  const cursor = fs.readFileSync(path.join(root, '.cursor', 'agents', 'validator.md'), 'utf8');
  assert.equal(frontmatterOf(cursor).fields.model, undefined, 'claude model names do not leak into cursor');

  const codex = fs.readFileSync(path.join(root, '.codex', 'agents', 'validator.toml'), 'utf8');
  assert.match(codex, new RegExp(`^# ${GENERATED_MARK}`));
  assert.match(codex, /^name = "validator"$/m);
  assert.match(codex, /^description = ".*\\"ensure\\" quality.*"$/m);
  assert.match(codex, /^developer_instructions = ".*Never patch, only judge\..*"$/m);
});

test('a second run changes nothing, a parked member loses its old files, hand-written files stay', () => {
  const root = project([['validator', VALIDATOR], ['scout', SCOUT.replace(/status: parked\n/, '')]]);
  assert.equal(exportMembers(root).written.length, 6);

  const again = exportMembers(root);
  assert.equal(again.written.length, 0);
  assert.equal(again.unchanged.length, 6);

  fs.writeFileSync(path.join(root, 'atris', 'team', 'scout', 'MEMBER.md'), SCOUT);
  const handWritten = path.join(root, '.claude', 'agents', 'validator.md');
  fs.writeFileSync(handWritten, '---\nname: validator\ndescription: mine\n---\nmine\n');

  const after = exportMembers(root);
  assert.deepEqual(after.removed.sort(), ['.claude/agents/scout.md', '.codex/agents/scout.toml', '.cursor/agents/scout.md']);
  assert.deepEqual(after.kept, ['.claude/agents/validator.md']);
  assert.equal(fs.readFileSync(handWritten, 'utf8'), '---\nname: validator\ndescription: mine\n---\nmine\n');
});

test('atris member export runs for real, and --dry-run writes nothing', () => {
  const root = project([['validator', VALIDATOR]]);
  const env = { ...process.env, ATRIS_SKIP_UPDATE_CHECK: '1' };

  const dry = spawnSync(process.execPath, [cli, 'member', 'export', '--dry-run'], { cwd: root, env, encoding: 'utf8' });
  assert.equal(dry.status, 0, dry.stderr);
  assert.match(dry.stdout, /Would write \.claude\/agents\/validator\.md/);
  assert.equal(fs.existsSync(path.join(root, '.claude')), false);

  const run = spawnSync(process.execPath, [cli, 'member', 'export'], { cwd: root, env, encoding: 'utf8' });
  assert.equal(run.status, 0, run.stderr);
  assert.match(run.stdout, /1 member exported to claude code, cursor, and codex, 3 files written/);
  assert.equal(fs.existsSync(path.join(root, '.claude', 'agents', 'validator.md')), true);
});

test('atris update --yes exports the team in a business project and in a plain project', () => {
  const env = { ...process.env, ATRIS_SKIP_UPDATE_CHECK: '1' };
  const business = project([['checker', VALIDATOR.replace('name: validator', 'name: checker')]]);
  fs.mkdirSync(path.join(business, '.atris'), { recursive: true });
  fs.writeFileSync(path.join(business, '.atris', 'business.json'), JSON.stringify({ name: 'Acme' }));
  const plain = project([['checker', VALIDATOR.replace('name: validator', 'name: checker')]]);

  for (const root of [business, plain]) {
    const run = spawnSync(process.execPath, [cli, 'update', '--yes'], { cwd: root, env, encoding: 'utf8' });
    assert.equal(run.status, 0, run.stderr);
    assert.match(run.stdout, /✓ Team: \d+ members? exported to claude code, cursor, and codex/);
    assert.equal(fs.existsSync(path.join(root, '.claude', 'agents', 'checker.md')), true, root);
    assert.equal(fs.existsSync(path.join(root, '.codex', 'agents', 'checker.toml')), true, root);
  }

  const dry = project([['checker', VALIDATOR]]);
  const plan = spawnSync(process.execPath, [cli, 'update', '--dry-run'], { cwd: dry, env, encoding: 'utf8' });
  assert.doesNotMatch(plan.stdout, /✓ Team:/);
  assert.equal(fs.existsSync(path.join(dry, '.claude', 'agents')), false);
});
